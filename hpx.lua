	-- PLAY EMOTE
	local function playEmote(name, id)
	
		local char = LocalPlayer.Character or LocalPlayer.CharacterAdded:Wait()
		local hum = char:FindFirstChildOfClass("Humanoid")
	
		if not hum then
			return
		end
	
		if hum.RigType == Enum.HumanoidRigType.R6 then
			warn("Emote só funciona em R15")
			return
		end
	
		if currentTrack and typeof(currentTrack) == "Instance" and currentTrack:IsA("AnimationTrack") then
			currentTrack:Stop()
		end
	
		currentTrack = nil
		local idNumber = tonumber(id)
	
		if not idNumber then
			return
		end
	
		local cleanName = tostring(name):gsub("⭐ ", "")
	
		local desc = hum:FindFirstChildOfClass("HumanoidDescription")
	
		if not desc then
			desc = Instance.new("HumanoidDescription")
			desc.Parent = hum
		end
	
		-- DELTA METHOD
		pcall(function()
			desc:AddEmote(cleanName, idNumber)
		end)
	
		task.wait(0.1)
	
		-- PLAY BY ID
		local ok, success, track = pcall(function()
			return hum:PlayEmoteAndGetAnimTrackById(idNumber)
		end)
	
		if ok then
			if typeof(success) == "Instance" and success:IsA("AnimationTrack") then
				currentTrack = success
				return
			end
	
			if typeof(track) == "Instance" and track:IsA("AnimationTrack") then
				currentTrack = track
				return
			end
		end
	
		-- PLAY BY NAME
		local okName = pcall(function()
			hum:PlayEmote(cleanName)
		end)
	
		if okName then
			return
		end
	
		warn("Não conseguiu tocar:", cleanName, idNumber)
	end
	
