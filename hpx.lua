	-- SEARCH
	function pesquisarCatalogo(texto)
	
		local resultado = {}
	
		texto = string.lower(texto or "")
	
		-- FAVORITOS
		if mostrandoFavoritos then
	
			for _,info in pairs(favoritos) do
	
				if texto == "" or string.find(string.lower(info[1]), texto) then
					table.insert(resultado,info)
				end
			end
	
		else
	
			if texto ~= "" then
	
				local ok, pages = pcall(function()
	
					local params = CatalogSearchParams.new()
					params.SearchKeyword = texto
					params.AssetTypes = {Enum.AvatarAssetType.EmoteAnimation}
					params.SortType = Enum.CatalogSortType.Relevance
					params.Limit = 30
	
					return AvatarEditorService:SearchCatalog(params)
				end)
	
				if ok and pages then
	
					for _,item in ipairs(pages:GetCurrentPage()) do
	
						if item.Name and item.Id then
	
							table.insert(resultado,{
								item.Name,
								item.Id
							})
						end
					end
				end
			end
		end
	
		refresh(resultado)
	end
	
